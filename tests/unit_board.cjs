const assert=require('node:assert/strict');
const board=require('../static/unit-board.js');
const u={id:1,active:true,number:'101',kind:'استوديو',floor:'1',cleaning:'ready'};
const S={today:'2026-10-23',units:[u],blocks:[],reservations:[]};
const stay=(status,departure,allocations)=>({id:1,status,departure,guest_name:'ضيف تجريبي',balance:100,allocations});
const a=(start,end,unit=1)=>({unit,start,end});
assert.equal(board.status(S,u).state,'vacant');
S.reservations=[stay('checked_in','2026-10-22',[a('2026-10-20','2026-10-22')])];
assert.equal(board.status(S,u).state,'departure','overdue guest still occupies the unit');
S.reservations=[stay('checked_out','2026-10-24',[a('2026-10-23','2026-10-24')])];
assert.equal(board.status(S,u).state,'vacant','billed night after checkout is not physical occupancy');
S.reservations=[stay('checked_in','2026-10-25',[a('2026-10-20','2026-10-22'),a('2026-10-22','2026-10-25',2)])];
assert.equal(board.status(S,u).state,'vacant','transferred old unit released');
S.reservations=[stay('confirmed','2026-10-25',[a('2026-10-23','2026-10-25')])];
assert.equal(board.status(S,u).state,'arrival');
S.blocks=[{unit_id:1,start:'2026-10-23',end:'2026-10-24'}];
assert.equal(board.status(S,u).state,'maintenance');
S.reservations=[stay('checked_in','2026-10-25',[a('2026-10-23','2026-10-25')])];
assert.equal(board.status(S,u).state,'occupied','physical guest takes priority over blocking');
const helpers={esc:String,money:String,openBtn:()=>'<button>تفاصيل</button>',table:()=>'<table></table>',navIcon:()=>'',search:''};
assert.match(board.render(S,helpers),/board-room/);
assert(board.control({dataset:{boardFilter:'vacant'}}));
assert.match(board.render(S,helpers),/لا توجد وحدات/);
assert(board.control({dataset:{boardFilter:'all'}}));
assert(board.control({dataset:{boardView:'list'}}));
assert.match(board.render(S,helpers),/<table>/);
assert(board.control({dataset:{boardView:'grid'}}));
console.log('Unit board: physical occupancy, transfers, maintenance, filters and views passed');
